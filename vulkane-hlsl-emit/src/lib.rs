//! IR to HLSL compute-shader lowering for [Unpopped](https://crates.io/crates/unpopped).
//!
//! Vulkane owns HLSL in the CireSnave ecosystem (ruling 2026-10-30). [`Hlsl`] emits a DXC-compilable
//! compute kernel for the scalar contiguous Elementwise path: `StructuredBuffer<T>` inputs named
//! `input{K}`, one `RWStructuredBuffer<T>` named `output`, a `[numthreads(256, 1, 1)]` entry taking
//! `uint3 tid : SV_DispatchThreadID`.
//!
//! ## A thin layer, by design (design note H3)
//!
//! The Slang dialect that [`vulkane_slang_emit::Slang`] writes for this path is already HLSL:
//! overloaded intrinsics, `StructuredBuffer`, `[numthreads]`, `asfloat(0x7fc00000u)` for non-finite
//! constants. So [`Hlsl`] does not copy the spellers. It lowers through `Slang` and changes the three
//! things that are the HLSL toolchain's, not Slang's:
//!
//! * the entry name prefix (`unpopped_hlsl_...`) and the generated-by header;
//! * the compiler-argument line: `// dxc: -denorm preserve` (see [`required_dxc_args`]) in place of
//!   `slangc`'s `-denorm-mode-fp32`;
//! * nothing else. In particular the bodies are byte-identical, which the tests assert.
//!
//! Bindings carry no `register(..)` clause on purpose: with DXC's `-spirv`, `t0`, `t1` and `u0` all
//! map to SPIR-V binding 0 unless `-fvk-*-shift` options are passed, so explicit registers would
//! collide. Declaration order gives bindings 0, 1, ..., N (inputs, then the output), the same layout
//! the Slang emitter has.
//!
//! The scope and the declined set are the Slang emitter's: scalar elementwise, no params, no
//! f16/bf16, no polyfilled ops. A decline from `Slang` is returned unchanged except that its text
//! still says `slang backend`; the variant is what callers match on.

use unpopped::backend::{Backend, DtypeSupport, GeneratedKernel, LowerError};
use unpopped::plan::KernelPlan;
use unpopped_vocab::{ElementKind, TargetId};
use vulkane_slang_emit::Slang;

const SLANG_HEADER: &str = "// Generated by unpopped (slang backend)";
const HLSL_HEADER: &str = "// Generated by unpopped (hlsl backend)";
const SLANG_PREFIX: &str = "unpopped_slang_";
const HLSL_PREFIX: &str = "unpopped_hlsl_";

/// The HLSL compute-shader backend. Lowers a [`KernelPlan`] to `.hlsl` source.
#[derive(Copy, Clone, Debug, Default)]
pub struct Hlsl;

/// The `dxc` arguments (beyond `-T cs_6_2 -E <entry> -spirv`) a kernel of `dtype` needs for its
/// f32 subnormals to follow IEEE (`-denorm preserve`, SPIR-V `DenormPreserve`). Empty for integer
/// and f64 kernels. Like Slang's, this is a compiler argument the consumer passes, not source text.
#[must_use]
pub fn required_dxc_args(dtype: ElementKind) -> &'static [&'static str] {
    match dtype {
        ElementKind::F32 | ElementKind::F32Strict => &["-denorm", "preserve"],
        _ => &[],
    }
}

/// Re-dialect a kernel the Slang emitter produced. Panics if the Slang output no longer has the
/// shape this relies on (a header, the entry prefix, at most one `// slangc:` line): a shape change
/// in `vulkane-slang-emit` must fail loudly here, not emit a mislabelled kernel.
fn retarget(k: &GeneratedKernel, dtype: ElementKind) -> GeneratedKernel {
    assert!(
        k.name.starts_with(SLANG_PREFIX),
        "slang emitter entry name changed: {}",
        k.name
    );
    assert_eq!(
        k.source.matches(SLANG_HEADER).count(),
        1,
        "slang emitter header changed:\n{}",
        k.source
    );
    let name = k.name.replacen(SLANG_PREFIX, HLSL_PREFIX, 1);
    let mut out = String::with_capacity(k.source.len());
    for line in k.source.lines() {
        if line.starts_with("// slangc:") {
            let args = required_dxc_args(dtype);
            if !args.is_empty() {
                out.push_str(&format!("// dxc: {}\n", args.join(" ")));
            }
            continue;
        }
        let line = line
            .replacen(SLANG_HEADER, HLSL_HEADER, 1)
            .replace(SLANG_PREFIX, HLSL_PREFIX);
        out.push_str(&line);
        out.push('\n');
    }
    GeneratedKernel::new(name, out)
}

impl Backend for Hlsl {
    fn name(&self) -> &str {
        "hlsl"
    }
    fn provider(&self) -> &str {
        "vulkane"
    }

    fn supports_dtype(&self, dtype: ElementKind, target: TargetId) -> DtypeSupport {
        Slang.supports_dtype(dtype, target)
    }

    fn lower(&self, plan: &KernelPlan<'_>) -> Result<GeneratedKernel, LowerError> {
        Slang.lower(plan).map(|k| retarget(&k, plan.dtype))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use unpopped::generate;
    use unpopped::ir::{OpDef, input};
    use unpopped_vocab::{ArchSku, OpCategory, OperandDesc, structure_key};

    fn key(dt: ElementKind) -> unpopped_vocab::StructureKey {
        let a = OperandDesc::new(1, &[1 << 20], &[1], dt, 4);
        structure_key(OpCategory::BinaryElementwise, &[a, a, a], ArchSku::Sm89)
    }

    fn pair(dt: ElementKind) -> (GeneratedKernel, GeneratedKernel) {
        let op = OpDef::elementwise("add", 2, &[dt], input(0) + input(1));
        (
            generate(&op, &key(dt), &Hlsl),
            generate(&op, &key(dt), &Slang),
        )
    }

    #[test]
    fn identity_and_dialect_markers() {
        assert_eq!(Hlsl.name(), "hlsl");
        let (h, _) = pair(ElementKind::F32);
        assert!(h.name.starts_with("unpopped_hlsl_add_"), "{}", h.name);
        assert!(h.source.contains(HLSL_HEADER), "{}", h.source);
        assert!(!h.source.contains("slang"), "{}", h.source);
    }

    #[test]
    fn float_kernels_name_dxc_denorm_and_integer_kernels_do_not() {
        let (f, _) = pair(ElementKind::F32);
        assert!(
            f.source.contains("// dxc: -denorm preserve\n"),
            "{}",
            f.source
        );
        let (i, _) = pair(ElementKind::I32);
        assert!(!i.source.contains("// dxc:"), "{}", i.source);
    }

    /// The thin-layer claim, checked: everything but the marker lines is the Slang text, byte for byte.
    #[test]
    fn body_is_byte_identical_to_the_slang_emitter() {
        for dt in [
            ElementKind::F32,
            ElementKind::F64,
            ElementKind::I32,
            ElementKind::U32,
        ] {
            let (h, s) = pair(dt);
            let strip = |t: &str| -> Vec<String> {
                t.lines()
                    .filter(|l| {
                        !l.starts_with("// Generated")
                            && !l.starts_with("// slangc:")
                            && !l.starts_with("// dxc:")
                    })
                    .map(|l| l.replace(SLANG_PREFIX, HLSL_PREFIX))
                    .collect()
            };
            assert_eq!(strip(&h.source), strip(&s.source), "{dt:?}");
        }
    }

    #[test]
    fn declines_match_the_slang_emitter() {
        let mut declined = 0;
        for tok in ["vulkan:sg32.arith-f16-i8", "vulkan:sg32.arith-f16"] {
            for dt in [
                ElementKind::F16,
                ElementKind::Bf16,
                ElementKind::F32,
                ElementKind::I64,
                ElementKind::I8,
            ] {
                let t = || TargetId::parse(tok).expect("valid token");
                let h = Hlsl.supports_dtype(dt, t()).is_supported();
                assert_eq!(
                    h,
                    Slang.supports_dtype(dt, t()).is_supported(),
                    "{tok} {dt:?}"
                );
                declined += usize::from(!h);
            }
        }
        // Control: the comparison saw both a decline (f16) and a pass (f32).
        assert!(declined > 0 && declined < 10, "declined {declined} of 10");
    }

    /// Device/toolchain validation: every emitted kernel compiles with `dxc` to SPIR-V. Needs `dxc`
    /// on PATH: without it the test returns early, UNLESS `VULKANE_REQUIRE_DXC` is set, when a
    /// missing `dxc` fails (the control that the check can run). Run locally with the Vulkan SDK.
    #[test]
    fn emitted_hlsl_compiles_with_dxc() {
        use std::process::Command;
        let have = Command::new("dxc").arg("-help").output().is_ok();
        if !have {
            assert!(
                std::env::var_os("VULKANE_REQUIRE_DXC").is_none(),
                "VULKANE_REQUIRE_DXC is set but `dxc` could not be run"
            );
            eprintln!("skipping: `dxc` not on PATH (set VULKANE_REQUIRE_DXC to make this fatal)");
            return;
        }
        let tmp = tempfile::tempdir().expect("private temp dir");
        let mut n = 0;
        for dt in [
            ElementKind::F32,
            ElementKind::F64,
            ElementKind::I32,
            ElementKind::U32,
            ElementKind::I64,
        ] {
            let (k, _) = pair(dt);
            let out = run_dxc(
                tmp.path(),
                &k.name,
                &k.source,
                &k.name,
                required_dxc_args(dt),
            );
            assert!(
                out.status.success(),
                "dxc failed for '{}':\n{}\n--- source ---\n{}",
                k.name,
                String::from_utf8_lossy(&out.stderr),
                k.source
            );
            n += 1;
        }
        assert_eq!(n, 5);
        // Negative control: a broken file is rejected, so the loop above can fail.
        let out = run_dxc(tmp.path(), "bad", "void main( {", "main", &[]);
        assert!(!out.status.success(), "dxc must reject a broken file");
    }

    /// Compile `src` (written as `<stem>.hlsl` in `dir`) with `dxc` to SPIR-V for `entry`.
    fn run_dxc(
        dir: &std::path::Path,
        stem: &str,
        src: &str,
        entry: &str,
        extra: &[&str],
    ) -> std::process::Output {
        let path = dir.join(format!("{stem}.hlsl"));
        std::fs::write(&path, src).expect("write .hlsl");
        std::process::Command::new("dxc")
            .args([
                "-T",
                "cs_6_2",
                "-E",
                entry,
                "-spirv",
                "-fspv-target-env=vulkan1.1",
            ])
            .args(extra)
            .arg(&path)
            .arg("-Fo")
            .arg(dir.join("out.spv"))
            .output()
            .expect("run dxc")
    }

    #[test]
    fn emitted_hlsl_relifts_through_the_hlsl_frontend() {
        use unpopped::convert::lift_elementwise;
        use unpopped::ir::ScalarExpr;
        use vulkane_hlsl_parse::HLSL;
        let op = OpDef::elementwise("mul", 2, &[ElementKind::F32], input(0) * input(1));
        let k = generate(&op, &key(ElementKind::F32), &Hlsl);
        let lifted = lift_elementwise(&HLSL, &k.source, "mul", &[ElementKind::F32])
            .expect("emitted HLSL must re-lift");
        assert_eq!(
            lifted.op.body,
            ScalarExpr::Mul(
                Box::new(ScalarExpr::Input(0)),
                Box::new(ScalarExpr::Input(1))
            ),
            "{}",
            k.source
        );
    }
}
